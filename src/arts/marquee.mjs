export function prepare(t, o) {
  return [...String(o.text || 'HELLO WORLD').toUpperCase().slice(0, 80)].map((c) => FONT[c] || FONT['?'])
}

export default function field(x, y, t, p, o, glyphs) {
  const c = p * Math.max(1, Math.round(Math.min(0.19, (1.6 * o.ey) / 7) / p)) // font pixel, on whole dots
  const row = Math.floor(y / c + 3.5)
  if (row < 0 || row > 6) return 0
  const cols = glyphs.length * 6 + 10 // each letter is 5 wide plus 1 space; 10 blank columns between repeats
  const col = (((Math.floor(x / c + t * 9) % cols) + cols) % cols) | 0
  const g = glyphs[Math.floor(col / 6)]
  if (!g || col % 6 === 5) return 0
  return g[row * 6 + (col % 6)] === '#' ? 1 : 0
}
